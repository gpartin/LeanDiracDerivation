"""Test the completed native carrier hull under timestep refinement.

The configuration dressing is derived exactly as in
``current_action_invariant_graph_completion``.  For each timestep, append only
the finite response generated by the centered update, verify that the reduced
configuration hull is invariant, and diagonalize its complete two-layer
monodromy.  This determines whether the remaining phase problem is only a
readout choice or includes a genuine growing native mode.
"""

from __future__ import annotations

import itertools
import json
from pathlib import Path

import numpy as np
import torch
from scipy.linalg import eig, eigvals, eigh, lu_factor, lu_solve

import canonical_noncoplanar_bifurcation_audit as native_time
import canonical_noncoplanar_box_transfer as native_box
