def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main() -> None:
    missing = [name for name in FILES if not (HERE / name).is_file()]
    result = {
        "status": "V4_SNAP_VS_CONDITIONAL_ARTIFACT_AUDIT",
        "files": {name: digest(HERE / name) for name in FILES if name not in missing},
        "missing": missing,
        "verdict": "PASS" if not missing else "FAIL",
        "claim_boundary": (
            "Hashes certify the movement-target research snapshot. They do "
            "not close the two-layer native embedding/current bridge, prove "
            "V4-006, admit a research action, or change canonical V40."),
    }
    (HERE / "snap_vs_conditional_artifact_audit.json").write_text(
        json.dumps(result, indent=2, allow_nan=False) + "\n",
        encoding="utf-8")
    print(json.dumps(result, indent=2, allow_nan=False))


if __name__ == "__main__":
    main()
