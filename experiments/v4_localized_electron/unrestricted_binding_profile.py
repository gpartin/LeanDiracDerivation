"""Unrestricted fixed-charge localized branch for the minimal binding action.

This test frees every complex Psi/chi component on the periodic lattice.  The
only constraints are the two Noether charges generated by the native phase
subgroups of the exact carrier.  The action under test is

  Ulocal = (rhoChi-R^2)^2/4 + g rhoChi rhoPsi/2
           + lambda rhoPsi^2/4,
  Uarea  = sum_C19 w |W_j-W_i|^2/(2 R^2),  W=chi x Psi,
  Uchi   = B s_chi sum_C19 w |chi_j-chi_i|^2/(2 sum_w).

The natural equal-action normalization has ``B*s_chi=1``, hence
``s_chi=1/B``.  Equal chi wave speed would instead require ``s_chi=1`` and is
not assumed.  The term contains no carrier geometry, corner label, preferred
direction, or Dirac data.  This is a feasibility calculation, not an admitted
action change.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
from scipy.optimize import least_squares

import localized_stability as native


HERE = Path(__file__).resolve().parent
WEIGHT_SUM = float(sum(weight for _, weight in native.DIRECTIONS))


def action_force(psi: np.ndarray, chi: np.ndarray, lam: float,
                 coupling: float, chi_stiffness: float,
                 psi_stiffness: float = 0.0):
    """Mass-normalized acceleration from the complete research action."""
    force_psi, force_chi = native.force(psi, chi)
    rho_psi = native.norm2(psi)[..., None]
    rho_chi = native.norm2(chi)[..., None]
    force_psi -= ((lam - 1.0) * rho_psi
                  + (coupling - 1.0) * rho_chi) * psi
    force_chi -= ((coupling - 1.0) * rho_psi * chi / native.B)
    force_chi -= (chi_stiffness / WEIGHT_SUM
                  * native.c19_dirichlet(chi))
    force_psi -= (psi_stiffness / WEIGHT_SUM
                  * native.c19_dirichlet(psi))
    return force_psi, force_chi


def phase_rates(omega_psi: float, omega_chi: float):
    return (np.asarray((omega_psi, omega_psi, omega_psi - omega_chi)),
            np.asarray((omega_chi, omega_chi, 0.0)))


def inertias(psi: np.ndarray, chi: np.ndarray):
    psi_all = float(np.sum(abs(psi)**2))
    psi_third = float(np.sum(abs(psi[..., 2])**2))
    chi_plane = float(native.B * np.sum(abs(chi[..., :2])**2))
    return np.asarray(((psi_all, -psi_third),
                       (-psi_third, psi_third + chi_plane)))


def charges(psi: np.ndarray, chi: np.ndarray,
            omega_psi: float, omega_chi: float):
    return inertias(psi, chi) @ np.asarray((omega_psi, omega_chi))


def rigid_seed(side: int, lam: float, coupling: float, amplitude_sq: float):
    psi, chi = native.carrier_fields(side, amplitude_sq)
    fp, fc = action_force(psi, chi, lam, coupling, 0.0)
    mask = native.norm2(psi) > 0
    active_chi = np.zeros_like(chi)
    active_chi[mask] = chi[mask]
    wp2 = float(-np.vdot(psi, fp).real / np.vdot(psi, psi).real)
    wc2 = float(-np.vdot(active_chi, fc).real
                / np.vdot(active_chi, active_chi).real)
    if min(wp2, wc2) <= 0:
        raise ValueError("seed does not have two real phase frequencies")
    return psi, chi, float(np.sqrt(wp2)), float(np.sqrt(wc2))


def solve_stage(initial: np.ndarray, side: int, lam: float, coupling: float,
                chi_stiffness: float, target_charge: np.ndarray,
                reference_psi: np.ndarray, reference_chi: np.ndarray,
                max_nfev: int):
    configuration_size = 12 * side**3
    scale = np.sqrt(configuration_size)
    psi_norm = max(float(np.linalg.norm(reference_psi)), 1.0)
    chi_plane_reference = reference_chi.copy()
    chi_plane_reference[..., 2] = 0
    chi_norm = max(float(np.linalg.norm(chi_plane_reference)), 1.0)
    carrier_sites = np.argwhere(native.norm2(reference_psi) > 0)
    anchor = tuple(int(value) for value in carrier_sites[0])
    # Replace two redundant Euler--Lagrange components by phase gauges.  The
    # dropped entries are precisely nonzero coordinates of the two symmetry
    # tangents at the reference carrier.
    site_flat = np.ravel_multi_index(anchor, (side, side, side))
    block = 12 * site_flat
    drop = np.asarray((block + 3, block + 10), dtype=int)

    def unpack(parameters):
        psi, chi = native.unpack(parameters[:configuration_size], side)
        return psi, chi, float(parameters[-2]), float(parameters[-1])

    def full_stationary(parameters):
        psi, chi, omega_psi, omega_chi = unpack(parameters)
        fp, fc = action_force(
            psi, chi, lam, coupling, chi_stiffness)
        rp, rc = phase_rates(omega_psi, omega_chi)
        return native.pack(fp + rp**2 * psi, fc + rc**2 * chi) / scale

    def residual(parameters):
        psi, chi, omega_psi, omega_chi = unpack(parameters)
        stationary = np.delete(full_stationary(parameters), drop)
        charge_error = ((charges(psi, chi, omega_psi, omega_chi)
                         - target_charge)
                        / np.maximum(abs(target_charge), 1.0))
        psi_gauge = np.vdot(reference_psi, psi).imag / psi_norm
        chi_gauge = np.vdot(chi_plane_reference, chi).imag / chi_norm
        return np.concatenate((stationary, charge_error,
                               (psi_gauge, chi_gauge)))

    solution = least_squares(
        residual, initial, jac="2-point", method="trf", x_scale="jac",
        ftol=2e-11, xtol=2e-11, gtol=2e-11, max_nfev=max_nfev,
        verbose=0)
    psi, chi, omega_psi, omega_chi = unpack(solution.x)
    raw = residual(solution.x)
    full_raw = full_stationary(solution.x)
    stationary_rms = float(np.linalg.norm(full_raw)
                           / np.sqrt(configuration_size))
    return (solution, psi, chi, omega_psi, omega_chi, stationary_rms,
            raw, full_raw)


def identity_metrics(psi: np.ndarray, chi: np.ndarray,
                     reference_psi: np.ndarray, reference_chi: np.ndarray):
    mask = native.norm2(reference_psi) > 0
    psi_total = max(float(np.sum(abs(psi)**2)), 1e-30)
    carrier_overlap = (abs(np.vdot(reference_psi[mask], psi[mask]))**2
                       / max(float(np.sum(abs(reference_psi[mask])**2)
                                   * np.sum(abs(psi[mask])**2)), 1e-30))
    vacuum = np.zeros_like(chi)
    vacuum[..., 2] = native.R
    return {
        "psi_carrier_overlap_sq": float(carrier_overlap),
        "psi_exterior_fraction": float(np.sum(abs(psi[~mask])**2)
                                       / psi_total),
        "chi_exterior_deviation_rms": float(np.linalg.norm(
            (chi - vacuum)[~mask]) / np.sqrt(3 * np.count_nonzero(~mask))),
        "chi_plane_charge_exterior_fraction": float(
            np.sum(abs(chi[~mask, :2])**2)
            / max(np.sum(abs(chi[..., :2])**2), 1e-30)),
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--side", type=int, default=3)
    parser.add_argument("--lambda-self", type=float, default=0.25)
    parser.add_argument("--coupling", type=float, default=1.0)
    parser.add_argument("--amplitude-sq", type=float, default=250.0)
    parser.add_argument("--stiffness-path", nargs="+", type=float,
                        default=(0.0, 1e-5, 3e-5, 1e-4, 3e-4,
                                 1 / 1197, 0.001))
    parser.add_argument("--max-nfev", type=int, default=80)
    parser.add_argument("--output", default="unrestricted_binding_profile.json")
    args = parser.parse_args()
    native.B = 1197.0
    reference_psi, reference_chi, omega_psi, omega_chi = rigid_seed(
        args.side, args.lambda_self, args.coupling, args.amplitude_sq)
    target_charge = charges(
        reference_psi, reference_chi, omega_psi, omega_chi)
    initial = np.concatenate((native.pack(reference_psi, reference_chi),
                              (omega_psi, omega_chi)))
    rows = []
    final_fields = None
    for stiffness in args.stiffness_path:
        solution, psi, chi, op, oc, rms, raw, full_raw = solve_stage(
            initial, args.side, args.lambda_self, args.coupling, stiffness,
            target_charge, reference_psi, reference_chi, args.max_nfev)
        metrics = identity_metrics(
            psi, chi, reference_psi, reference_chi)
        row = {
            "chi_stiffness": stiffness,
            "solver_success": bool(solution.success),
            "solver_status": int(solution.status),
            "solver_nfev": int(solution.nfev),
            "cost": float(solution.cost),
            "optimality": float(solution.optimality),
            "stationary_rms": rms,
            "largest_stationary_component": float(np.max(abs(full_raw))),
            "charge_relative_residual": [float(x) for x in raw[-4:-2]],
            "omega_psi": op,
            "omega_chi": oc,
            **metrics,
        }
        rows.append(row)
        if rms > 1e-7 or max(abs(raw[-4:-2])) > 1e-7:
            break
        initial = solution.x
        final_fields = (psi, chi, solution.x)
    result = {
        "status": "V4_UNRESTRICTED_FIXED_CHARGE_BINDING_BRANCH",
        "canonical_action_changed": False,
        "research_action_admitted": False,
        "side": args.side,
        "lambda_self": args.lambda_self,
        "density_coupling": args.coupling,
        "initial_amplitude_sq": args.amplitude_sq,
        "target_charges": [float(x) for x in target_charge],
        "chi_stiffness_provenance": (
            "positive reciprocal normalized C19 gradient; equal action "
            "normalization gives stiffness=1/B because chi inertia is B"),
        "rows": rows,
        "claim_boundary": (
            "Existence/identity continuation only. A surviving branch still "
            "requires a constrained-index and full-spectrum calculation."),
    }
    output = HERE / args.output
    output.write_text(json.dumps(result, indent=2, allow_nan=False) + "\n",
                      encoding="utf-8")
    if final_fields is not None:
        np.savez_compressed(output.with_suffix(".npz"),
                            psi=final_fields[0], chi=final_fields[1],
                            parameters=final_fields[2])
    print(json.dumps(result, indent=2, allow_nan=False))


if __name__ == "__main__":
    main()
