"""Derive the minimal native dressing of the all-center carrier envelope.

Starting from the translation-equivariant four-component envelope, form its
native acceleration residual.  Adjoin only the singular directions actually
generated by that residual and test closure.  Then use the generalized native
stiffness spectrum to select an invariant subspace of the original dimension
whose projection back to the undressed carrier is nonsingular.  Finally test
that dressed configuration graph against the actual two-layer centered update.

No force or action is changed.  The construction is an offline readout and
invariant-subspace calculation.
"""

from __future__ import annotations

import itertools
import json
from pathlib import Path

import numpy as np
from scipy.linalg import eigh, lu_factor, lu_solve

import canonical_noncoplanar_bifurcation_audit as native_time
import current_action_localized_envelope_closure as envelope
import personal_touch_unit_geometric_canonical as canonical


HERE = Path(__file__).resolve().parent


def channel_fractions(vectors: np.ndarray) -> dict:
    shaped = vectors.reshape(5, 5, 5, 4, 3, -1)
    power = np.sum(shaped**2, axis=(0, 1, 2, 5))
    total = max(float(np.sum(power)), 1e-30)
    return {
        "Psi_fraction": float(np.sum(power[:2]) / total),
        "chi_fraction": float(np.sum(power[2:]) / total),
        "component_fractions": [float(value/total)
                                for value in np.sum(power, axis=0)],
    }


def main() -> None:
    bare = np.load(canonical.CACHE)
    additions = np.load(HERE / "personal_touch_activated_bond_basis_v2_cache.npz")
    stiffness = (bare["stiffness"]
                 + additions["hessian_carrier_carrier_chi"]
                 + additions["hessian_carrier_carrier_Psi_tight_frame"])
    mass = bare["mass"]
    gyro = bare["gyro"]
    acceleration = -stiffness / np.diag(mass)[:, None]
    psi_frame, chi_frame, sites = envelope.carrier_frames(bare["rest"])
    offsets = list(itertools.product((-2, -1, 0, 1, 2), repeat=3))
    scales = {"plus": 0.00104831247009457,
              "minus": 0.0010251705436500206}
    rows = []
    for flavor, basis in envelope.flavor_bases().items():
        q = envelope.orth(envelope.raw_columns(
            basis, psi_frame, chi_frame, sites, offsets, scales[flavor]))
        response = acceleration @ q
        residual = response - q @ (q.T @ response)
        u, singular, _ = np.linalg.svd(residual, full_matrices=False)
        keep = singular > 1e-10 * max(float(singular[0]), 1.0)
        normal = u[:, keep]
        hull = np.column_stack((q, normal))
        hull_closure = envelope.closure(acceleration, hull)

        reduced_stiffness = hull.T @ stiffness @ hull
        reduced_mass = hull.T @ mass @ hull
        eigenvalues, eigenvectors = eigh(
            reduced_stiffness, reduced_mass, check_finite=False)
        physical_modes = hull @ eigenvectors
        normal_fraction = np.sum((normal.T @ physical_modes)**2, axis=0) / np.sum(
            physical_modes**2, axis=0)
        selected = np.argsort(normal_fraction)[:q.shape[1]]
        dressed = envelope.orth(physical_modes[:, selected])
        projection = q.T @ dressed
        projection_singular = np.linalg.svd(projection, compute_uv=False)
        dressed_closure = envelope.closure(acceleration, dressed)
        tail = normal.T @ dressed @ np.linalg.inv(projection)

        dt = native_time.DT
        left = mass/dt + gyro/2
        backward = mass/dt - gyro/2
        zero = dt*stiffness - 2*mass/dt
        factor = lu_factor(left)
        forward_image = -lu_solve(factor, zero @ dressed)
        backward_image = -lu_solve(factor, backward @ dressed)
        projector = dressed @ dressed.T
        forward_residual = forward_image - projector @ forward_image
        backward_residual = backward_image - projector @ backward_image
        two_layer_residual = np.column_stack((
            forward_residual, backward_residual))
        two_layer_response = np.column_stack((
            forward_image, backward_image))
        u2, singular2, _ = np.linalg.svd(
            two_layer_residual, full_matrices=False)
        keep2 = singular2 > 1e-10 * max(float(singular2[0]), 1.0)
        update_hull = np.column_stack((dressed, u2[:, keep2]))
        update_projector = update_hull @ update_hull.T
        update_hull_response = np.column_stack((
            -lu_solve(factor, zero @ update_hull),
            -lu_solve(factor, backward @ update_hull)))
        update_hull_residual = (
            update_hull_response
            - update_projector @ update_hull_response)

        rows.append({
            "flavor": flavor,
            "undressed_real_rank": int(q.shape[1]),
            "initial_relative_cross_block": float(
                np.linalg.norm(residual)/np.linalg.norm(response)),
            "generated_dressing_rank": int(normal.shape[1]),
            "generated_dressing_channels": channel_fractions(
                normal * singular[keep][None, :]),
            "expanded_hull_rank": int(hull.shape[1]),
            "expanded_hull_relative_cross_block": hull_closure[
                "relative_cross_block"],
            "same_rank_dressed_projection_min_singular": float(
                projection_singular[-1]),
            "same_rank_dressed_projection_condition": float(
                projection_singular[0]/projection_singular[-1]),
            "same_rank_dressed_tail_rms": float(
                np.linalg.norm(tail)/np.sqrt(tail.size)),
            "same_rank_dressed_tail_operator_norm": float(
                np.linalg.norm(tail, 2)),
            "same_rank_dressed_relative_cross_block": dressed_closure[
                "relative_cross_block"],
            "two_layer_same_rank_relative_cross_block": float(
                np.linalg.norm(two_layer_residual)
                / np.linalg.norm(two_layer_response)),
            "two_layer_generated_extra_rank": int(np.sum(keep2)),
            "two_layer_generated_channels": channel_fractions(
                u2[:, keep2] * singular2[keep2][None, :]),
            "two_layer_expanded_hull_rank": int(update_hull.shape[1]),
            "two_layer_expanded_hull_relative_cross_block": float(
                np.linalg.norm(update_hull_residual)
                / np.linalg.norm(update_hull_response)),
            "reduced_generalized_stiffness_min": float(eigenvalues[0]),
            "reduced_generalized_stiffness_max": float(eigenvalues[-1]),
        })
    configuration_pass = max(
        row["same_rank_dressed_relative_cross_block"] for row in rows) < 1e-10
    two_layer_pass = max(
        row["two_layer_same_rank_relative_cross_block"] for row in rows) < 1e-10
    result = {
        "status": "V4_CURRENT_ACTION_INVARIANT_GRAPH_COMPLETION",
        "canonical_action_changed": False,
        "research_action_admitted": False,
        "rows": rows,
        "configuration_verdict": (
            "SAME_RANK_NATIVE_DRESSED_CONFIGURATION_SECTOR_PASS"
            if configuration_pass else
            "SAME_RANK_NATIVE_DRESSED_CONFIGURATION_SECTOR_FAIL"),
        "two_layer_verdict": (
            "SAME_RANK_NATIVE_TWO_LAYER_SECTOR_PASS"
            if two_layer_pass else
            "SAME_RANK_NATIVE_TWO_LAYER_SECTOR_REQUIRES_PHASE_DRESSING"),
        "interpretation": (
            "The action itself generates a finite out-of-plane Psi dressing "
            "of the carrier envelope. It can be reduced to a same-dimension, "
            "well-conditioned invariant configuration graph. The actual "
            "centered update adds a second finite response through its "
            "co-rotating gyro/time-layer structure; that phase dressing must "
            "be reduced before current can be compared."),
        "claim_boundary": (
            "This is a linear tangent result at the exact rest orbit. It does "
            "not prove nonlinear translation, current closure, or V4-006, and "
            "it changes no action."),
    }
    (HERE / "current_action_invariant_graph_completion.json").write_text(
        json.dumps(result, indent=2, allow_nan=False) + "\n",
        encoding="utf-8")
    print(json.dumps(result, indent=2, allow_nan=False))


if __name__ == "__main__":
    main()
