"""Derive the cubical Clifford links directly from the live Psi rays.

No fixed corner matrix is used to construct the links.  On each edge of the
occupied cube the normalized complex overlap of the two native ``Psi`` rays
is used as the parallel transporter.  This file tests whether the three edge
flip operators generated by those live phases square to one and anticommute.
The central product then supplies an orientation/flavor involution with two
four-dimensional eigenspaces.  This is a geometry gate, not an action change.
"""

from __future__ import annotations

import itertools
import json
from pathlib import Path

import numpy as np
import torch

import canonical_noncoplanar_box_transfer as box
import cube_incidence_nonlinear_action as native_action
import cubical_edge_shift_channels as cubical


HERE = Path(__file__).resolve().parent
SIDE = 5
CORNERS = tuple(itertools.product((0, 1), repeat=3))


def occupied_rays(rest: np.ndarray, which: str = "psi") -> np.ndarray:
    psi, chi = box.unpack(torch.tensor(rest), SIDE)
    psi, chi = psi.numpy(), chi.numpy()
    sites = [tuple(int(value) for value in site)
             for site in np.argwhere(np.sum(abs(psi)**2, axis=-1) > 1e-12)]
    sites.sort()
    field = psi if which == "psi" else chi
    values = np.stack([field[site] for site in sites])
    return values/np.linalg.norm(values, axis=1)[:, None]


def live_generator(rays: np.ndarray, axis: int) -> np.ndarray:
    result = np.zeros((8, 8), dtype=complex)
    for corner, bits in enumerate(CORNERS):
        target_bits = list(bits)
        target_bits[axis] ^= 1
        target = CORNERS.index(tuple(target_bits))
        overlap = np.vdot(rays[corner], rays[target])
        result[corner, target] = overlap/abs(overlap)
    return result


def diagonal_intertwiner(source: list[np.ndarray],
                         target: list[np.ndarray]) -> np.ndarray:
    """Derive D with target_a = D source_a D^dagger from edge links."""
    phases = np.full(8, np.nan+1j*np.nan, dtype=complex)
    phases[0] = 1
    changed = True
    while changed:
        changed = False
        for axis in range(3):
            for corner, bits in enumerate(CORNERS):
                target_bits = list(bits)
                target_bits[axis] ^= 1
                neighbor = CORNERS.index(tuple(target_bits))
                if (not np.isnan(phases[corner].real)
                        and np.isnan(phases[neighbor].real)):
                    ratio = target[axis][corner, neighbor] \
                        / source[axis][corner, neighbor]
                    phases[neighbor] = np.conj(ratio/phases[corner])
                    changed = True
    return np.diag(phases)


def rank(matrix: np.ndarray) -> int:
    return int(np.linalg.matrix_rank(matrix, tol=1e-10))


def main() -> None:
    bare, _ = native_action.expected_blocks()
    rays = occupied_rays(bare["rest"])
    identity = np.eye(8, dtype=complex)
    generators = [live_generator(rays, axis) for axis in range(3)]
    chi_rays = occupied_rays(bare["rest"], "chi")
    chi_generators = [live_generator(chi_rays, axis) for axis in range(3)]
    intertwiner = diagonal_intertwiner(generators, chi_generators)
    intertwiner_defects = [float(np.linalg.norm(
        chi_generators[axis]
        - intertwiner@generators[axis]@intertwiner.conj().T))
        for axis in range(3)]
    # The carrier occupies a native C2 plane.  Its remaining live edge axis is
    # the normal, and the relative Psi/chi connection on that axis supplies
    # the grading.  No historical beta enters this construction.
    beta_native = 1j*generators[2]@chi_generators[2]
    orientation = 1j*generators[0]@generators[1]@generators[2]
    projectors = ((identity+orientation)/2, (identity-orientation)/2)
    rows = []
    for axis, generator in enumerate(generators):
        rows.append({
            "axis": axis,
            "square_defect": float(np.linalg.norm(
                generator@generator-identity)),
            "hermiticity_defect": float(np.linalg.norm(
                generator.conj().T-generator)),
            "minimum_edge_overlap_magnitude": float(min(
                abs(np.vdot(rays[corner], rays[CORNERS.index(tuple(
                    (1-bits[0], bits[1], bits[2]) if axis == 0 else
                    (bits[0], 1-bits[1], bits[2]) if axis == 1 else
                    (bits[0], bits[1], 1-bits[2])))]))
                for corner, bits in enumerate(CORNERS))),
        })
    anticommutators = [
        float(np.linalg.norm(generators[first]@generators[second]
                             + generators[second]@generators[first]))
        for first in range(3) for second in range(first+1, 3)
    ]
    orientation_rows = {
        "square_defect": float(np.linalg.norm(
            orientation@orientation-identity)),
        "hermiticity_defect": float(np.linalg.norm(
            orientation.conj().T-orientation)),
        "generator_commutator_defects": [float(np.linalg.norm(
            orientation@generator-generator@orientation))
            for generator in generators],
        "eigenspace_ranks": [rank(projector) for projector in projectors],
        "projector_defects": [float(np.linalg.norm(
            projector@projector-projector)) for projector in projectors],
    }
    beta_rows = {
        "construction": "i times live-Psi normal link times live-chi normal link",
        "carrier_plane_normal_axis": 2,
        "square_defect": float(np.linalg.norm(
            beta_native@beta_native-identity)),
        "hermiticity_defect": float(np.linalg.norm(
            beta_native.conj().T-beta_native)),
        "transport_anticommutator_defects": [float(np.linalg.norm(
            beta_native@generator+generator@beta_native))
            for generator in generators],
        "historical_beta_validation_defect": float(np.linalg.norm(
            beta_native-cubical.beta())),
    }
    tolerance = 1e-12
    passed = (
        max(row["square_defect"] for row in rows) < tolerance
        and max(row["hermiticity_defect"] for row in rows) < tolerance
        and max(anticommutators) < tolerance
        and orientation_rows["square_defect"] < tolerance
        and orientation_rows["eigenspace_ranks"] == [4, 4]
        and max(intertwiner_defects) < tolerance
        and beta_rows["square_defect"] < tolerance
        and beta_rows["hermiticity_defect"] < tolerance
        and max(beta_rows["transport_anticommutator_defects"]) < tolerance)
    result = {
        "status": "V4_LIVE_PSI_CLIFFORD_LINK_GEOMETRY",
        "canonical_action_changed": False,
        "research_action_admitted": False,
        "construction": (
            "normalized Hermitian overlap phases of native complex Psi rays "
            "on the twelve cube edges"),
        "fixed_Dirac_or_copy_matrix_used_in_construction": False,
        "generator_rows": rows,
        "cross_axis_anticommutator_defects": anticommutators,
        "orientation_involution": orientation_rows,
        "live_chi_link_intertwiner_defects": intertwiner_defects,
        "native_beta_grading": beta_rows,
        "verdict": (
            "LIVE_PSI_CHI_LINKS_DERIVE_CLIFFORD_SECTORS_AND_BETA"
            if passed else "LIVE_PSI_LINK_CLIFFORD_GATE_FAILED"),
        "claim_boundary": (
            "Exact algebra at the retained rest carrier. It does not yet "
            "prove that a reciprocal action transports or preserves these "
            "live sectors away from rest."),
    }
    output = HERE/"live_clifford_link_geometry.json"
    output.write_text(json.dumps(result, indent=2, allow_nan=False)+"\n",
                      encoding="utf-8")
    print(json.dumps(result, indent=2, allow_nan=False))


if __name__ == "__main__":
    main()
