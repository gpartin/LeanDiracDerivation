"""Compare a self-contained extended native packet to discrete Dirac.

This replaces the rejected compact-support hop.  The eight-corner algebra is
an internal fiber at every envelope center.  A periodic Gaussian envelope is
lifted through the already-derived overlapping-cube Psi--chi synthesis.  Its
previous layer and independent target layer are generated by the C19 Dirac
symbol; the native action then advances the same current/previous fields.

Dirac supplies only the comparator and initial phase relation.  It never
enters the native action, forces, or update.
"""

from __future__ import annotations

import itertools
import json
import os
from pathlib import Path

import numpy as np
from scipy.linalg import expm, lu_factor, lu_solve

