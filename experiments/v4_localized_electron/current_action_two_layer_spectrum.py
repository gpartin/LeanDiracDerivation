HERE = Path(__file__).resolve().parent


def local_potential(raw: torch.Tensor) -> torch.Tensor:
    psi, chi = native_box.unpack(raw, 5)
    rho_psi = native_box.squared_norm(psi)
    rho_chi = native_box.squared_norm(chi)
    return torch.sum(
        0.25*(rho_chi-native_time.CHI0**2)**2
        + 0.5*rho_chi*rho_psi + 0.25*rho_psi**2)


def bond_potential(raw: torch.Tensor) -> torch.Tensor:
    return native_box.potential(raw, 5)-local_potential(raw)


def complex_directional_hessian(function, point: np.ndarray,
                                direction: np.ndarray) -> float:
    origin = torch.tensor(point, dtype=torch.float64)
    result = 0.0
    for part in (direction.real, direction.imag):
        vector = torch.tensor(part, dtype=torch.float64)
        _value, product = torch.autograd.functional.hvp(
            function, origin, vector, create_graph=False, strict=True)
        result += float(torch.dot(vector, product))
    return result


def charge_gradient(rest: np.ndarray, mass: np.ndarray, dt: float,
                    theta: float, field: str) -> np.ndarray:
    """Gradient of the physical two-layer U(1) charge in rotating coordinates.

    The previous perturbation in the co-rotating recurrence is converted back
    to the physical layer before differentiating the native discrete charge
    ``(q_n-q_{n-1})^T M J q_n / dt``.
    """
    dimension = rest.size
    rotation = native_spectrum.rotation_matrix(dimension, theta)
    left = rotation.T @ rest
    generator = np.zeros((dimension, dimension))
    shaped = np.arange(dimension).reshape(5, 5, 5, 4, 3)
    if field == "Psi":
        real = shaped[..., 0, :].ravel()
        imag = shaped[..., 1, :].ravel()
    elif field == "chi":
        real = shaped[..., 2, :].ravel()
        imag = shaped[..., 3, :].ravel()
    else:
        raise ValueError(field)
    generator[real, imag] = -1
    generator[imag, real] = 1
    right_gradient = (
        mass @ (generator @ rest)
        + generator.T @ (mass @ (rest-left))) / dt
    left_gradient = -(mass @ (generator @ rest)) / dt
    return np.concatenate((right_gradient, rotation @ left_gradient))


def dressed_configuration(stiffness: np.ndarray, mass: np.ndarray,
                          rest: np.ndarray) -> np.ndarray:
    acceleration = -stiffness / np.diag(mass)[:, None]
    psi_frame, chi_frame, sites = envelope.carrier_frames(rest)
    offsets = list(itertools.product((-2, -1, 0, 1, 2), repeat=3))
    basis = envelope.flavor_bases()["plus"]
    q = envelope.orth(envelope.raw_columns(
        basis, psi_frame, chi_frame, sites, offsets,
        0.00104831247009457))
    response = acceleration @ q
    residual = response - q @ (q.T @ response)
    u, singular, _ = np.linalg.svd(residual, full_matrices=False)
    normal = u[:, singular > 1e-10*max(float(singular[0]), 1.0)]
    hull = np.column_stack((q, normal))
    values, vectors = eigh(
        hull.T @ stiffness @ hull, hull.T @ mass @ hull,
        check_finite=False)
    physical = hull @ vectors
    fraction = np.sum((normal.T @ physical)**2, axis=0) / np.sum(
        physical**2, axis=0)
    selected = np.argsort(fraction)[:q.shape[1]]
    return envelope.orth(physical[:, selected])


def timestep_row(stiffness: np.ndarray, mass: np.ndarray,
                 gyro: np.ndarray, dressed: np.ndarray,
                 dt: float, vectors: bool,
                 stiffness_parts: dict[str, np.ndarray],
                 rest: np.ndarray) -> dict:
    factor = lu_factor(mass/dt + gyro/2)
    forward = -lu_solve(
        factor, (dt*stiffness - 2*mass/dt) @ dressed)
    backward = -lu_solve(factor, (mass/dt - gyro/2) @ dressed)
    residual = np.column_stack((
        forward-dressed@(dressed.T@forward),
        backward-dressed@(dressed.T@backward)))
    u, singular, _ = np.linalg.svd(residual, full_matrices=False)
    extra = u[:, singular > 1e-10*max(float(singular[0]), 1.0)]
    hull = envelope.orth(np.column_stack((dressed, extra)))
    forward_hull = -lu_solve(
        factor, (dt*stiffness - 2*mass/dt) @ hull)
    backward_hull = -lu_solve(
        factor, (mass/dt - gyro/2) @ hull)
    f = hull.T @ forward_hull
    g = hull.T @ backward_hull
    identity = np.eye(hull.shape[1])
    monodromy = np.block([[f, g], [identity, np.zeros_like(identity)]])
    closure_residual = np.column_stack((
        forward_hull-hull@f, backward_hull-hull@g))
    if vectors:
        values, modes = eig(monodromy, check_finite=False, overwrite_a=True)
        target = envelope.orth(np.vstack((hull.T@dressed, hull.T@dressed)))
        score = np.sum(abs(target.T@modes)**2, axis=0) / np.sum(
            abs(modes)**2, axis=0)
    else:
        values = eigvals(monodromy, check_finite=False, overwrite_a=True)
        score = None
    modulus = abs(values)
    growing = modulus > 1 + 1e-7
    row = {
        "dt": dt,
        "configuration_hull_rank": int(hull.shape[1]),
        "phase_space_dimension": int(monodromy.shape[0]),
        "hull_relative_cross_block": float(
            np.linalg.norm(closure_residual)
            / np.linalg.norm(np.column_stack((forward_hull, backward_hull)))),
        "maximum_multiplier_modulus": float(max(modulus)),
        "growing_multiplier_count_at_1e-7": int(np.sum(growing)),
        "maximum_growth_rate": float(np.log(max(modulus))/dt),
        "positive_phase_count": int(np.sum(np.angle(values) > 1e-9)),
        "negative_phase_count": int(np.sum(np.angle(values) < -1e-9)),
        "real_axis_count": int(np.sum(abs(np.angle(values)) <= 1e-9)),
    }
    if score is not None:
        order = np.argsort(score)[::-1]
        row.update({
            "growing_mode_target_overlap_min": float(min(score[growing])),
            "growing_mode_target_overlap_max": float(max(score[growing])),
            "growing_mode_target_overlap_mean": float(np.mean(score[growing])),
            "growing_modes_with_target_overlap_above_0p99": int(np.sum(
                growing & (score > 0.99))),
            "target_overlap_rank_boundary_1000": float(score[order[999]]),
            "target_overlap_next_mode": float(score[order[1000]]),
        })
        fastest = int(np.argmax(modulus))
        coordinate = hull @ modes[:hull.shape[1], fastest]
        phase_coordinate = np.concatenate((
            coordinate, hull @ modes[hull.shape[1]:, fastest]))
        np.savez_compressed(
            HERE / "current_action_fastest_mode.npz",
            current=coordinate,
            previous=hull @ modes[hull.shape[1]:, fastest],
            multiplier=values[fastest])
        denominator = float(np.vdot(coordinate, mass @ coordinate).real)
        shaped = coordinate.reshape(5, 5, 5, 4, 3)
        power = np.sum(abs(shaped)**2, axis=(0, 1, 2))
        row["fastest_growing_mode"] = {
            "multiplier_real": float(values[fastest].real),
            "multiplier_imag": float(values[fastest].imag),
            "multiplier_modulus": float(modulus[fastest]),
            "growth_rate": float(np.log(modulus[fastest])/dt),
            "target_overlap": float(score[fastest]),
            "generalized_stiffness_contributions": {
                name: float(np.vdot(
                    coordinate, matrix @ coordinate).real/denominator)
                for name, matrix in stiffness_parts.items()
            },
            "field_component_power_fractions": (
                power/np.sum(power)).tolist(),
        }
        local_curvature = complex_directional_hessian(
            local_potential, rest, coordinate)/denominator
        bond_curvature = complex_directional_hessian(
            bond_potential, rest, coordinate)/denominator
        psi_selector = np.zeros(rest.size)
        selector_shape = psi_selector.reshape(5, 5, 5, 4, 3)
        selector_shape[..., :2, :] = 1
        centrifugal = -native_time.CHI0**2*float(
            np.vdot(coordinate, (np.diag(mass)*psi_selector)*coordinate).real
            / denominator)
        row["fastest_growing_mode"]["bare_V40_curvature_breakdown"] = {
            "local_potential": local_curvature,
            "C19_area_bond_potential": bond_curvature,
            "co_rotating_centrifugal": centrifugal,
            "reconstructed_total": (
                local_curvature+bond_curvature+centrifugal),
            "matrix_total": row["fastest_growing_mode"][
                "generalized_stiffness_contributions"]["bare_V40"],
            "discrete_rotating_frame_remainder": (
                row["fastest_growing_mode"][
                    "generalized_stiffness_contributions"]["bare_V40"]
                - (local_curvature+bond_curvature+centrifugal)),
            "minimum_additional_positive_curvature_for_neutrality": (
                -row["fastest_growing_mode"][
                    "generalized_stiffness_contributions"]["bare_V40"]),
        }
        theta = float(np.arccos(1-dt**2*native_time.CHI0**2/2))
        charge_rows = {}
        for field in ("Psi", "chi"):
            full_gradient = charge_gradient(rest, mass, dt, theta, field)
            gradient = np.concatenate((
                hull.T @ full_gradient[:rest.size],
                hull.T @ full_gradient[rest.size:]))
            derivative = np.dot(gradient, modes[:, fastest])
            cosine = abs(derivative) / (
                np.linalg.norm(gradient)*np.linalg.norm(modes[:, fastest]))
            invariance = gradient @ monodromy-gradient
            charge_rows[field] = {
                "derivative_real": float(derivative.real),
                "derivative_imag": float(derivative.imag),
                "normalized_tangent_cosine": float(cosine),
                "left_invariance_relative_residual": float(
                    np.linalg.norm(invariance)/np.linalg.norm(gradient)),
            }
        row["fastest_growing_mode"]["native_charge_tangents"] = charge_rows
    return row


def main() -> None:
    bare = np.load(canonical.CACHE)
    additions = np.load(HERE / "personal_touch_activated_bond_basis_v2_cache.npz")
    stiffness = (bare["stiffness"]
                 + additions["hessian_carrier_carrier_chi"]
                 + additions["hessian_carrier_carrier_Psi_tight_frame"])
    stiffness_parts = {
        "bare_V40": bare["stiffness"],
        "carrier_carrier_chi_tight_frame": additions[
            "hessian_carrier_carrier_chi"],
        "carrier_carrier_Psi_tight_frame": additions[
            "hessian_carrier_carrier_Psi_tight_frame"],
        "total": stiffness,
    }
    dressed = dressed_configuration(stiffness, bare["mass"], bare["rest"])
    dt0 = native_time.DT
    rows = [timestep_row(
        stiffness, bare["mass"], bare["gyro"], dressed, dt0/factor,
        vectors=(factor == 1), stiffness_parts=stiffness_parts,
        rest=bare["rest"])
        for factor in (1, 2, 4)]
    rates = [row["maximum_growth_rate"] for row in rows]
    converged = abs(rates[-1]-rates[-2])/max(abs(rates[-1]), 1e-30) < 0.05
    result = {
        "status": "V4_CURRENT_ACTION_TWO_LAYER_SPECTRUM",
        "canonical_action_changed": False,
        "research_action_admitted": False,
        "rows": rows,
        "growth_rate_refinement_relative_change": float(
            abs(rates[-1]-rates[-2])/max(abs(rates[-1]), 1e-30)),
        "verdict": (
            "TWO_LAYER_NATIVE_GROWTH_CONVERGED"
            if converged and rows[-1]["growing_multiplier_count_at_1e-7"] > 0
            else "TWO_LAYER_SPECTRUM_INCONCLUSIVE"),
        "claim_boundary": (
            "This is the linear spectrum of the finite native hull derived "
            "from the exact rest orbit. It is not a nonlinear lifetime or a "
            "universal no-go. A converged growing mode blocks promotion of "
            "this action/readout branch until its native cause is repaired."),
    }
    (HERE / "current_action_two_layer_spectrum.json").write_text(
        json.dumps(result, indent=2, allow_nan=False) + "\n",
        encoding="utf-8")
    print(json.dumps(result, indent=2, allow_nan=False))


if __name__ == "__main__":
    main()
