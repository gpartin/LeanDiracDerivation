"""Test the exact cube-phase stiffness as the missing seventh response.

The six scalar pair connections have zero restoring stiffness on the surviving
001 corner character.  This calculation adds the already-derived positive
area-bilinear phase square as a variable response.  Its scale is measured in
the native unit 1/chi0^2.  Continuous optimization is diagnostic only; full
validation is restricted to simple factors generated by the cube eigenvalues
8 and 12 and their ratio.
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
from scipy.linalg import eig
from scipy.optimize import differential_evolution, minimize

import canonical_noncoplanar_bifurcation_audit as native_time
import cube_geometry_bifurcation_solve as solve
import current_action_two_layer_spectrum as current
import personal_touch_unit_geometric_canonical as canonical


HERE = Path(__file__).resolve().parent


def main() -> None:
    prior = json.loads((HERE/"cube_geometry_bifurcation_solve.json").read_text())
    bare, mass0, gyro0, stiffness_with_unit_phase = solve.base_matrices()
    phase_hessian = np.load(HERE/"area_bilinear_phase_action_hessian.npz")[
        "normalized_hessian"]
    phase_unit = phase_hessian/native_time.CHI0**2
    stiffness0 = stiffness_with_unit_phase-phase_unit
    scalar = [solve.load_blocks(feature) for feature in solve.FEATURES]
    natural = native_time.B*native_time.CHI0

    seed6 = np.asarray(
        prior["continuous_solution"]["coefficients_in_B_chi0_units"])
    seed_m = mass0.copy()
    seed_g = gyro0.copy()
    seed_k = stiffness0+phase_unit
    for coefficient, block in zip(seed6, scalar, strict=True):
        seed_m += natural*coefficient*block["mass"]
        seed_g += natural*coefficient*block["gyro"]
        seed_k += natural*coefficient*block["stiffness"]
    hull = solve.invariant_hull(seed_m, seed_g, seed_k, bare["rest"])
    values = eig(solve.monodromy(seed_m, seed_g, seed_k, hull),
                 right=False, check_finite=False)
    _, _, growing = solve.real_growing_configuration(
        hull, solve.monodromy(seed_m, seed_g, seed_k, hull))
    columns = [growing]
    for block in scalar:
        for kind in ("mass", "gyro", "stiffness"):
            columns.append(block[kind]@growing)
    columns.append(phase_unit@growing)
    reduced = solve.envelope.orth(np.column_stack(columns))

    base = {"mass": mass0, "gyro": gyro0, "stiffness": stiffness0}
    deltas = scalar+[{
        "mass": np.zeros_like(mass0),
        "gyro": np.zeros_like(gyro0),
        "stiffness": phase_unit,
    }]
    scales = [natural]*6+[1.0]
    reduced_base = solve.reduced_blocks(base, reduced)
    reduced_deltas = [solve.reduced_blocks(block, reduced) for block in deltas]

    def objective(x: np.ndarray) -> float:
        matrices = {kind: reduced_base[kind].copy()
                    for kind in ("mass", "gyro", "stiffness")}
        for coefficient, scale, block in zip(x, scales, reduced_deltas,
                                             strict=True):
            for kind in matrices:
                matrices[kind] += scale*coefficient*block[kind]
        minimum_mass = float(np.linalg.eigvalsh(matrices["mass"])[0])
        if minimum_mass <= 1e-8:
            return 1000+1000*abs(minimum_mass)
        multipliers = eig(solve.reduced_monodromy(**matrices),
                          right=False, check_finite=False)
        growth = float(np.log(max(abs(multipliers)))/native_time.DT)
        return max(growth, 0.0)+1e-7*float(np.dot(x, x))

    bounds = [(0.0, 2.5)]+[(-2.5, 2.5)]*5+[(0.0, 12.0)]
    fit = differential_evolution(
        objective, bounds, seed=40061, popsize=10, maxiter=55,
        tol=1e-8, polish=False, updating="immediate", workers=1)
    local = minimize(
        objective, fit.x, method="Nelder-Mead",
        options={"maxiter": 1500, "xatol": 1e-9, "fatol": 1e-11})
    optimum = local.x if local.fun <= fit.fun else fit.x

    # Factors generated by exact restricted-C19 character eigenvalues 8, 12.
    phase_factors = (0.0, 1/12, 1/8, 2/12, 2/8, 8/12, 1.0,
                     12/8, 2.0, 8.0, 12.0)
    rows = [{
        "label": "continuous_inverse_solution",
        "coefficients": optimum.tolist(),
        "projected_objective": float(objective(optimum)),
    }]
    for factor in phase_factors:
        candidate = optimum.copy()
        candidate[6] = factor
        rows.append({
            "label": f"C19_phase_factor_{factor:g}",
            "coefficients": candidate.tolist(),
            "projected_objective": float(objective(candidate)),
        })
    rows.sort(key=lambda row: row["projected_objective"])

    full_rows = []
    for row in rows[:6]:
        x = np.asarray(row["coefficients"])
        matrices = {kind: base[kind].copy()
                    for kind in ("mass", "gyro", "stiffness")}
        for coefficient, scale, block in zip(x, scales, deltas, strict=True):
            for kind in matrices:
                matrices[kind] += scale*coefficient*block[kind]
        dressed = current.dressed_configuration(
            matrices["stiffness"], matrices["mass"], bare["rest"])
        full = solve.spectrum.spectrum_row(
            matrices["mass"], matrices["gyro"], matrices["stiffness"],
            dressed, native_time.DT)
        full_rows.append({
            "label": row["label"],
            "coefficients": row["coefficients"],
            **full,
        })
    best = min(full_rows, key=lambda row: row["maximum_growth_rate"])
    result = {
        "status": "V4_CUBE_PHASE_BIFURCATION_COMPLETION",
        "canonical_action_changed": False,
        "research_action_admitted": False,
        "cube_eigenvalues": [8, 12],
        "phase_coefficient_unit": "1/chi0^2",
        "initial_growth_rate": float(
            np.log(max(abs(values)))/native_time.DT),
        "reduced_rank": int(reduced.shape[1]),
        "continuous_inverse_solution": {
            "six_coefficients_in_B_chi0_units_then_phase_factor": (
                optimum.tolist()),
            "projected_objective": float(objective(optimum)),
            "optimizer_success": bool(fit.success or local.success),
        },
        "projected_rows": rows,
        "full_spectrum_rows": full_rows,
        "best_full_spectrum": best,
        "verdict": (
            "CUBE_PHASE_GEOMETRY_FULL_SPECTRUM_PASS"
            if best["growing_multiplier_count_at_1e_minus_7"] == 0
            else "CUBE_PHASE_GEOMETRY_RETAINS_GROWTH"),
        "claim_boundary": (
            "The continuous inverse point has no coefficient provenance. "
            "Only a listed exact C19 factor can be considered geometric, and "
            "even a linear pass would still require nonlinear and motion "
            "gates before admission."),
    }
    (HERE/"cube_phase_bifurcation_completion.json").write_text(
        json.dumps(result, indent=2, allow_nan=False)+"\n", encoding="utf-8")
    print(json.dumps(result, indent=2, allow_nan=False))


if __name__ == "__main__":
    main()
