HERE = Path(__file__).resolve().parent
SIDE = 5
OFFSETS = list(itertools.product((-2, -1, 0, 1, 2), repeat=3))
COMPARATOR_MASS = float(os.environ.get(
    "LFM_DIRAC_COMPARATOR_MASS", str(native_time.CHI0)))


def c19_first_symbol(momentum, transport_scale=1.0):
    result = np.zeros(3)
    for offset, weight in c19.DIRECTIONS:
        direction = np.asarray(offset, dtype=float)
        result += weight*direction*np.sin(momentum@direction)
    return transport_scale*result/12.0


def flavor_bases():
    identity = np.eye(8, dtype=complex)
    flavor = cubical.flavor()
    result = {}
    for name, projector in (
            ("plus", (identity+flavor)/2),
            ("minus", (identity-flavor)/2)):
        values, vectors = np.linalg.eigh(projector)
        result[name] = vectors[:, values > 0.5]
    return result


def compressed_clifford(basis):
    alpha = [basis.conj().T@cubical.gamma(axis)@basis for axis in range(3)]
    beta = basis.conj().T@cubical.beta()@basis
    return alpha, beta


def dirac_step(field, alpha, beta, sign, dt=native_time.DT,
               frequency_branch="positive", transport_scale=1.0):
    fourier = np.fft.fftn(field, axes=(0, 1, 2))
    result = np.empty_like(fourier)
    frequencies = 2*np.pi*np.fft.fftfreq(SIDE)
    for index in itertools.product(range(SIDE), repeat=3):
        momentum = np.asarray([frequencies[value] for value in index])
        transport = c19_first_symbol(momentum, transport_scale)
        # The native tangent blocks are expressed in the carrier's rotating
        # frame.  Remove the rest phase belonging to the selected laboratory
        # frequency branch before comparing the perturbation update.  The
        # proved rest carrier advances with positive complex phase, so its
        # matching Dirac sector is the negative-frequency branch.
        branch = 1 if frequency_branch == "positive" else -1
        hamiltonian = COMPARATOR_MASS*(beta-branch*np.eye(4))
        for axis in range(3):
            hamiltonian = hamiltonian+transport[axis]*alpha[axis]
        result[index] = expm(
            -1j*sign*dt*hamiltonian)@fourier[index]
    return np.fft.ifftn(result, axes=(0, 1, 2))


def centered_dirac_step(field, alpha, beta, sign, dt=native_time.DT,
                        frequency_branch="positive", transport_scale=1.0):
    """Exact centered-time Dirac phase in the carrier co-rotating frame.

    Squaring the Hermitian cubical Dirac Hamiltonian gives the native
    second-order oscillator.  A centered/Verlet layer therefore advances an
    energy eigenmode by theta=acos(1-dt^2 E^2/2), not by dt*E.  The common
    rest phase theta0 is removed only after constructing that exact lab-frame
    step.  This is a comparator/readout correction; no native force uses it.
    """
    fourier = np.fft.fftn(field, axes=(0, 1, 2))
    result = np.empty_like(fourier)
    frequencies = 2*np.pi*np.fft.fftfreq(SIDE)
    theta0 = float(np.arccos(1-dt**2*COMPARATOR_MASS**2/2))
    for index in itertools.product(range(SIDE), repeat=3):
        momentum = np.asarray([frequencies[value] for value in index])
        transport = c19_first_symbol(momentum, transport_scale)
        hamiltonian = COMPARATOR_MASS*beta
        for axis in range(3):
            hamiltonian = hamiltonian+transport[axis]*alpha[axis]
        energy = float(np.sqrt(COMPARATOR_MASS**2+transport@transport))
        argument = 1-dt**2*energy**2/2
        theta = float(np.arccos(np.clip(argument, -1.0, 1.0)))
        lab_step = (np.cos(theta)*np.eye(4)
                    - 1j*sign*np.sin(theta)*hamiltonian/energy)
        branch = 1 if frequency_branch == "positive" else -1
        corotating = np.exp(1j*sign*branch*theta0)*lab_step
        result[index] = corotating@fourier[index]
    return np.fft.ifftn(result, axes=(0, 1, 2))


def packet(axis, sign, alpha, beta, dt=native_time.DT, width=1.35,
           carrier_wave_number=0.35, centered_time=False,
           frequency_branch="positive", transport_scale=1.0):
    coordinates = np.asarray(OFFSETS, dtype=float).reshape(SIDE, SIDE, SIDE, 3)
    distance2 = np.sum(coordinates**2, axis=-1)
    carrier_momentum = np.zeros(3)
    if axis == 3:
        carrier_momentum[:] = sign*carrier_wave_number/np.sqrt(3)
    else:
        carrier_momentum[axis] = sign*carrier_wave_number
    envelope_value = np.exp(-distance2/(2*width**2))*np.exp(
        1j*np.einsum("...a,a->...", coordinates, carrier_momentum))
    h0 = COMPARATOR_MASS*beta
    transport = c19_first_symbol(carrier_momentum, transport_scale)
    for component in range(3):
        h0 = h0+transport[component]*alpha[component]
    values, vectors = np.linalg.eigh(h0)
    if frequency_branch not in ("positive", "negative"):
        raise ValueError(f"unknown frequency branch: {frequency_branch}")
    spinor = vectors[:, (np.argmax(values) if frequency_branch == "positive"
                         else np.argmin(values))]
    current = envelope_value[..., None]*spinor
    stepper = centered_dirac_step if centered_time else dirac_step
    previous = stepper(current, alpha, beta, -1, dt, frequency_branch,
                       transport_scale)
    following = stepper(current, alpha, beta, 1, dt, frequency_branch,
                        transport_scale)
    return previous, current, following, carrier_momentum


def real_coordinates(field):
    values = []
    flat = field.reshape(-1, 4)
    for center in range(flat.shape[0]):
        for component in range(4):
            values.extend((flat[center, component].real,
                           flat[center, component].imag))
    return np.asarray(values)


def circular_center(field):
    density = np.sum(abs(field)**2, axis=-1)
    result = []
    for axis in range(3):
        shape = [1, 1, 1]
        shape[axis] = SIDE
        phase = np.exp(2j*np.pi*np.arange(SIDE)/SIDE).reshape(shape)
        value = np.sum(density*phase)
        result.append(float(np.angle(value)*SIDE/(2*np.pi)))
    return np.asarray(result)


def wrapped_shift(first, second):
    delta = second-first
    return (delta+SIDE/2) % SIDE-SIDE/2


def main():
    bare, matrices = action.expected_blocks()
    mass, gyro, stiffness = (matrices[name]
                             for name in ("mass", "gyro", "stiffness"))
    factor = lu_factor(mass/native_time.DT+gyro/2)
    advance = -lu_solve(
        factor, native_time.DT*stiffness-2*mass/native_time.DT)
    memory = -lu_solve(factor, mass/native_time.DT-gyro/2)
    psi_frame, chi_frame, sites = envelope.carrier_frames(bare["rest"])
    scales = {}
    prior = json.loads((HERE/"cube_incidence_dirac_envelope_gate.json").read_text())
    for row in prior["rows"]:
        case = next(item for item in row["cases"]
                    if item["envelope"] == "all_125_centers")
        scales[row["flavor"]] = complex(
            case["chi_scale_real"], case["chi_scale_imag"])

    rows = []
    for flavor, basis in flavor_bases().items():
        alpha, beta = compressed_clifford(basis)
        raw = envelope.raw_columns(
            basis, psi_frame, chi_frame, sites, OFFSETS, scales[flavor])
        cases = []
        native_columns = []
        target_columns = []
        metadata = []
        for axis in range(4):
            for sign in (-1, 1):
                previous, current, following, momentum = packet(
                    axis, sign, alpha, beta)
                q_previous = raw@real_coordinates(previous)
                q_current = raw@real_coordinates(current)
                q_target = raw@real_coordinates(following)
                native_columns.append(advance@q_current+memory@q_previous)
                target_columns.append(q_target)
                metadata.append((axis, sign, momentum, current, following))
        native_matrix = np.column_stack(native_columns)
        target_matrix = np.column_stack(target_columns)
        recovered, *_ = np.linalg.lstsq(raw, native_matrix, rcond=1e-10)
        projected = raw@recovered
        for column, (axis, sign, momentum, current, following) in enumerate(metadata):
            native = native_matrix[:, column]
            target = target_matrix[:, column]
            native_field = (recovered[:, column, None].reshape(-1, 2)
                            @np.asarray((1.0, 1.0j))).reshape(
                                SIDE, SIDE, SIDE, 4)
            cases.append({
                "direction": "diagonal" if axis == 3 else "xyz"[axis],
                "sign": sign,
                "carrier_momentum": momentum.tolist(),
                "native_vs_discrete_dirac_relative_error": float(
                    np.linalg.norm(native-target)/np.linalg.norm(target)),
                "native_outside_spatial_lift_fraction": float(
                    np.linalg.norm(native-projected[:, column])
                    / max(np.linalg.norm(native), 1e-30)),
                "dirac_center_shift": wrapped_shift(
                    circular_center(current), circular_center(following)).tolist(),
                "native_center_shift": wrapped_shift(
                    circular_center(current), circular_center(native_field)).tolist(),
            })
        rows.append({"flavor": flavor, "cases": cases})
    worst = max(case["native_vs_discrete_dirac_relative_error"]
                for row in rows for case in row["cases"])
    result = {
        "status": "V4_CUBE_INCIDENCE_EXTENDED_PACKET_GATE",
        "canonical_action_changed": False,
        "research_action_admitted": False,
        "packet": (
            "self-contained periodic Gaussian four-component envelope with "
            "native joint Psi-chi overlapping-cube lift"),
        "comparison_frame": (
            "carrier co-rotating frame: H_relative = H_Dirac - chi0 I on "
            "the positive-frequency packet"),
        "rows": rows,
        "worst_native_vs_discrete_dirac_relative_error": worst,
        "verdict": (
            "EXTENDED_PACKET_TANGENT_PASS" if worst < 1e-3 else
            "EXTENDED_PACKET_TANGENT_NOT_CLOSED"),
        "claim_boundary": (
            "One-step tangent packet comparison on the side-five rest orbit. "
            "It is not a nonlinear moving branch, large-box convergence, "
            "current proof, or V4-006 pass."),
    }
    (HERE/"cube_incidence_extended_packet_gate.json").write_text(
        json.dumps(result, indent=2, allow_nan=False)+"\n", encoding="utf-8")
    print(json.dumps(result, indent=2, allow_nan=False))


if __name__ == "__main__":
    main()
